"""gate_90_isa_coverage — ADR-0063 V1: instruction-coverage tracker + baseline.

Two checks, both fast/deterministic (no sim; the full log collection is
dv/coverage/collect.sh):
  1. Tool correctness: the ISA-coverage ingester parses Spike disasm lines, normalizes
     pseudos to their base op, buckets by extension, and — critically — gives NO credit
     for hitting an excluded scope-cut op (green-wash guard G7).
  2. Baseline thresholds on the committed report (dv/coverage/isa_cov_report.json,
     regenerated by collect.sh): scalar ISA fully exercised, Zve32x at/above baseline,
     exclusion ledger frozen (G6), no excluded op credited.

Authority note (G1): this is COMPLETENESS (did we exercise the encoding), NOT correctness
— every test counted here is itself Spike-lockstep verified elsewhere.
"""
import json
